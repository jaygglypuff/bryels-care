import { notFound } from "next/navigation";
import { requireContext } from "@/lib/auth/context";
import { DomainError } from "@/lib/errors";
import { type ReportOutput, printReport } from "@/modules/reports";
import { Logo } from "@/ui/brand";
import { EmptyState } from "@/ui/core";
import { PrintButton } from "./print-button";

export const dynamic = "force-dynamic";
export const metadata = { title: "Report" };

/**
 * Printable report (ADR-026: browser print / "Save as PDF"). Treated as an export: needs
 * analytics.report.export plus the module export permission and is audited (analytics.report.printed).
 */
export default async function ReportPrintPage({ params, searchParams }: { params: Promise<{ code: string }>; searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  const ctx = await requireContext();
  const { code } = await params;
  const sp = await searchParams;
  const raw: Record<string, string> = {};
  for (const [k, v] of Object.entries(sp)) {
    const s = Array.isArray(v) ? v[0] : v;
    if (s) raw[k] = s;
  }
  let out: ReportOutput;
  try {
    out = await printReport(ctx, code, raw);
  } catch (e) {
    if (e instanceof DomainError && e.code === "not_found") notFound();
    if (e instanceof DomainError)
      return (
        <main className="mx-auto max-w-xl p-6">
          <EmptyState title="This report cannot be printed">{e.message}</EmptyState>
        </main>
      );
    throw e;
  }
  const meta: [string, string][] = [...out.filters, ["Generated at", out.generatedAtText], ["Generated by", out.generatedBy], ["Data freshness", out.freshness], ["Value label", `${out.valueLabel} (computed from posted records)`], ["Rows", String(out.rowCount)]];
  return (
    <main className="min-h-dvh bg-[#e9e7e1] py-6 print:bg-white print:py-0">
      <style>{`
        @page { size: A4 landscape; margin: 12mm; }
        @media print { thead { display: table-header-group; } tr { break-inside: avoid; } }
      `}</style>
      <div className="no-print mx-auto mb-4 flex max-w-[297mm] items-center justify-between gap-3 px-4">
        <a href={`/reports/${out.code}`} className="text-[14px] text-primary-text hover:underline">← Back to the report</a>
        <PrintButton />
      </div>
      <article className="mx-auto w-full max-w-[297mm] overflow-x-auto bg-white p-[12mm] text-[11px] leading-snug text-black shadow-sm print:overflow-visible print:p-0 print:shadow-none">
        <header className="flex items-start justify-between gap-6 border-b-2 border-black pb-3">
          <div>
            <Logo className="mb-1 h-[36px] w-auto" />
            <p>{out.organizationName}</p>
          </div>
          <div className="text-right">
            <p className="text-[16px] font-bold">{out.title}</p>
            <p className="font-mono">{out.code}</p>
          </div>
        </header>
        <table className="my-3">
          <tbody>
            {meta.map(([k, v]) => (
              <tr key={k}>
                <th className="pr-3 text-left align-top font-semibold">{k}</th>
                <td>{v}</td>
              </tr>
            ))}
          </tbody>
        </table>
        {out.truncated && <p className="mb-2 border border-amber-700 p-2">Truncated: only the first {out.cap.toLocaleString("en-PH")} rows are included. Narrow the filters for the rest.</p>}
        {out.rows.length === 0 ? (
          <p className="border p-2">No rows match these filters.</p>
        ) : (
          <table className="w-full border-collapse">
            <thead>
              <tr>
                {out.columns.map((c) => (
                  <th key={c.key} className={`border border-gray-400 bg-gray-100 px-1.5 py-1 text-left ${c.numeric ? "text-right" : ""}`}>{c.header}</th>
                ))}
              </tr>
            </thead>
            <tbody>
              {out.rows.map((r, i) => (
                <tr key={i}>
                  {out.columns.map((c) => (
                    <td key={c.key} className={`border border-gray-300 px-1.5 py-0.5 align-top ${c.numeric ? "text-right tabular-nums" : ""}`}>{r[c.key] ?? ""}</td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        )}
        {out.summary.length > 0 && (
          <table className="mt-2">
            <tbody>
              {out.summary.map(([k, v]) => (
                <tr key={k}>
                  <th className="pr-3 text-left font-semibold">{k}</th>
                  <td>{v}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        <section className="mt-3">
          <p className="font-semibold">Footnotes</p>
          <ol className="list-decimal pl-5">
            {out.footnotes.map((f, i) => (
              <li key={i}>{f}</li>
            ))}
          </ol>
        </section>
      </article>
    </main>
  );
}
