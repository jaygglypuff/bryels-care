import { sql } from "drizzle-orm";
import { check, index, integer, jsonb, pgTable, text, timestamp, uniqueIndex, uuid, type AnyPgColumn } from "drizzle-orm/pg-core";
import { createdAt, id, updatedAt } from "./_common";
import { organizations, sites, users } from "./identity";
import { batchStateTransitions, batches } from "./production";
import { routingSteps } from "./engineering";
import { generatedDocuments } from "./documents";
import { fileAttachments } from "./files";

/**
 * BMR closure, controlled reopen / amendment and hybrid paper pages (Wave 2 W2D, E-3-06:
 * US-3-19, US-3-20; docs/data-model.md §6.2, docs/reports-and-templates.md §2.5, §2.6).
 *
 * Closure and reopen state lives here rather than on `batches` so the batch row stays owned by the
 * execution stream: `closed_at` = latest batch_closures.closed_at, `reopen_count` = executed
 * batch_reopen_requests. Closures and amendments are append-only (service + src/db/sql/w2d.sql).
 */

const inList = (col: AnyPgColumn, values: readonly string[]) => sql`${col} in (${sql.raw(values.map((v) => `'${v}'`).join(", "))})`;

/** One row per closure of a batch (1 = first closure, n + 1 after each reopen). Never updated. */
export const batchClosures = pgTable(
  "batch_closures",
  {
    id: id(),
    organizationId: uuid("organization_id").notNull().references(() => organizations.id),
    siteId: uuid("site_id").notNull().references(() => sites.id),
    batchId: uuid("batch_id").notNull().references(() => batches.id),
    closureNo: integer("closure_no").notNull(),
    /** released | rejected: the decided state the batch was closed from. */
    fromState: text("from_state").notNull(),
    batchStateTransitionId: uuid("batch_state_transition_id").references(() => batchStateTransitions.id),
    /** The BMR generated by the closure (CONTROLLED COPY, or AMENDED rev n after a reopen). */
    generatedDocumentId: uuid("generated_document_id").notNull().references(() => generatedDocuments.id),
    /** Snapshot of the completeness checks that passed (evidence; the checks are re-run on every closure). */
    checks: jsonb("checks").notNull(),
    reservationsReleased: integer("reservations_released").notNull().default(0),
    note: text("note"),
    closedBy: uuid("closed_by").notNull().references(() => users.id),
    closedAt: timestamp("closed_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("batch_closures_batch_no_uq").on(t.batchId, t.closureNo),
    check("batch_closures_no_ck", sql`${t.closureNo} >= 1`),
    check("batch_closures_from_ck", inList(t.fromState, ["released", "rejected"])),
  ],
);

export const REOPEN_REQUEST_STATUSES = ["pending", "reopened", "rejected", "withdrawn"] as const;
/** Where a reopened batch goes: back to its decided state (record-only amendment) or to QA re-review. */
export const REOPEN_TARGET_STATES = ["released", "rejected", "quarantined"] as const;

/**
 * CX-REOPEN request (docs/permissions-matrix.md §5.3, A-PM-07): requested by a holder of
 * production.batch.admin; decided through approval_decisions (record_type `batch_reopen`,
 * record_id = this row). Executed (batch moves out of `closed`) when the last step approves.
 */
export const batchReopenRequests = pgTable(
  "batch_reopen_requests",
  {
    id: id(),
    organizationId: uuid("organization_id").notNull().references(() => organizations.id),
    siteId: uuid("site_id").notNull().references(() => sites.id),
    batchId: uuid("batch_id").notNull().references(() => batches.id),
    /** Which closure this request reopens (batch_closures.closure_no). */
    closureNo: integer("closure_no").notNull(),
    status: text("status").notNull().default("pending"),
    targetState: text("target_state").notNull(),
    reason: text("reason").notNull(),
    /** What will be amended (sections / fields), as stated by the requester. */
    amendmentScope: text("amendment_scope").notNull(),
    requestedBy: uuid("requested_by").notNull().references(() => users.id),
    requestedAt: timestamp("requested_at", { withTimezone: true }).notNull().defaultNow(),
    decidedAt: timestamp("decided_at", { withTimezone: true }),
    decisionNote: text("decision_note"),
    /** reopen_no = 1 for the first executed reopen of the batch, then 2, … (the "AMENDED rev n"). */
    reopenNo: integer("reopen_no"),
    reopenedAt: timestamp("reopened_at", { withTimezone: true }),
    batchStateTransitionId: uuid("batch_state_transition_id").references(() => batchStateTransitions.id),
    idempotencyKey: text("idempotency_key"),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex("batch_reopen_requests_one_pending_uq").on(t.batchId).where(sql`${t.status} = 'pending'`),
    uniqueIndex("batch_reopen_requests_reopen_no_uq").on(t.batchId, t.reopenNo).where(sql`${t.reopenNo} is not null`),
    uniqueIndex("batch_reopen_requests_org_idem_uq").on(t.organizationId, t.idempotencyKey).where(sql`${t.idempotencyKey} is not null`),
    index("batch_reopen_requests_batch_idx").on(t.batchId),
    check("batch_reopen_requests_status_ck", inList(t.status, REOPEN_REQUEST_STATUSES)),
    check("batch_reopen_requests_target_ck", inList(t.targetState, REOPEN_TARGET_STATES)),
    check("batch_reopen_requests_reason_ck", sql`length(trim(${t.reason})) >= 10 and length(trim(${t.amendmentScope})) >= 5`),
    check(
      "batch_reopen_requests_reopened_ck",
      sql`(${t.status} = 'reopened') = (${t.reopenNo} is not null and ${t.reopenedAt} is not null)`,
    ),
  ],
);

export const AMENDMENT_SECTIONS = [
  "header",
  "materials",
  "process_steps",
  "line_clearance",
  "packaging_reconciliation",
  "output_yield",
  "qc",
  "deviations",
  "remarks",
  "attachments",
  "other",
] as const;

/**
 * Append-only amendment entries made while a batch is reopened. The previous value is kept next to
 * the corrected one and both print in the BMR (struck through + reason). A wrong amendment is
 * corrected by a new row that supersedes it, never by editing.
 */
export const batchAmendments = pgTable(
  "batch_amendments",
  {
    id: id(),
    organizationId: uuid("organization_id").notNull().references(() => organizations.id),
    siteId: uuid("site_id").notNull().references(() => sites.id),
    batchId: uuid("batch_id").notNull().references(() => batches.id),
    reopenRequestId: uuid("reopen_request_id").notNull().references(() => batchReopenRequests.id),
    amendmentNo: integer("amendment_no").notNull(),
    section: text("section").notNull(),
    /** What is corrected, e.g. "Step 4 Mixing and cutting, reading" or "Line 2 Palm oil". */
    reference: text("reference").notNull(),
    previousValue: text("previous_value").notNull(),
    correctedValue: text("corrected_value").notNull(),
    reason: text("reason").notNull(),
    supersedesId: uuid("supersedes_id").references((): AnyPgColumn => batchAmendments.id),
    idempotencyKey: text("idempotency_key"),
    recordedBy: uuid("recorded_by").notNull().references(() => users.id),
    recordedAt: timestamp("recorded_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("batch_amendments_batch_no_uq").on(t.batchId, t.amendmentNo),
    uniqueIndex("batch_amendments_org_idem_uq").on(t.organizationId, t.idempotencyKey).where(sql`${t.idempotencyKey} is not null`),
    check("batch_amendments_section_ck", inList(t.section, AMENDMENT_SECTIONS)),
    check("batch_amendments_reason_ck", sql`length(trim(${t.reason})) >= 5`),
  ],
);

/** issued (blank page printed) → attached (scan uploaded, transcription declared) → reviewed | returned → attached …; issued|returned → void. */
export const PAPER_RECORD_STATUSES = ["issued", "attached", "returned", "reviewed", "void"] as const;

/**
 * Hybrid paper record page (docs/reports-and-templates.md §2.5, A-RPT-06, A-PROC-37): a blank
 * page printed for a routing step, completed by hand, transcribed into the system, scanned and
 * attached, and confirmed by a reviewer who is not the transcriber. Both records are retained.
 */
export const batchPaperRecords = pgTable(
  "batch_paper_records",
  {
    id: id(),
    organizationId: uuid("organization_id").notNull().references(() => organizations.id),
    siteId: uuid("site_id").notNull().references(() => sites.id),
    batchId: uuid("batch_id").notNull().references(() => batches.id),
    routingStepId: uuid("routing_step_id").references(() => routingSteps.id),
    stepNo: integer("step_no").notNull(),
    stepName: text("step_name").notNull(),
    /** routing_steps.record_mode at issue (electronic | paper_then_transcribe | paper_only). */
    recordMode: text("record_mode").notNull(),
    pageNo: integer("page_no").notNull(),
    /** Printed on the page and quoted when transcribing: <batch number>-P<nn>. */
    paperReference: text("paper_reference").notNull(),
    status: text("status").notNull().default("issued"),
    /** The blank page as a generated document (DOC number, QR, hash). */
    generatedDocumentId: uuid("generated_document_id").references(() => generatedDocuments.id),
    fileAttachmentId: uuid("file_attachment_id").references(() => fileAttachments.id),
    transcriptionNote: text("transcription_note"),
    transcribedBy: uuid("transcribed_by").references(() => users.id),
    transcribedAt: timestamp("transcribed_at", { withTimezone: true }),
    reviewedBy: uuid("reviewed_by").references(() => users.id),
    reviewedAt: timestamp("reviewed_at", { withTimezone: true }),
    reviewNote: text("review_note"),
    voidedBy: uuid("voided_by").references(() => users.id),
    voidedAt: timestamp("voided_at", { withTimezone: true }),
    voidReason: text("void_reason"),
    issuedBy: uuid("issued_by").notNull().references(() => users.id),
    issuedAt: timestamp("issued_at", { withTimezone: true }).notNull().defaultNow(),
    idempotencyKey: text("idempotency_key"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex("batch_paper_records_batch_page_uq").on(t.batchId, t.pageNo),
    uniqueIndex("batch_paper_records_org_idem_uq").on(t.organizationId, t.idempotencyKey).where(sql`${t.idempotencyKey} is not null`),
    index("batch_paper_records_batch_idx").on(t.batchId, t.status),
    check("batch_paper_records_status_ck", inList(t.status, PAPER_RECORD_STATUSES)),
    check("batch_paper_records_mode_ck", inList(t.recordMode, ["electronic", "paper_then_transcribe", "paper_only"])),
    check("batch_paper_records_page_ck", sql`${t.pageNo} >= 1`),
    check(
      "batch_paper_records_attached_ck",
      sql`${t.status} not in ('attached', 'reviewed') or (${t.fileAttachmentId} is not null and ${t.transcribedBy} is not null and ${t.transcribedAt} is not null)`,
    ),
    check("batch_paper_records_reviewed_ck", sql`${t.status} <> 'reviewed' or (${t.reviewedBy} is not null and ${t.reviewedAt} is not null)`),
    check("batch_paper_records_void_ck", sql`${t.status} <> 'void' or (${t.voidedBy} is not null and ${t.voidedAt} is not null and ${t.voidReason} is not null)`),
  ],
);
