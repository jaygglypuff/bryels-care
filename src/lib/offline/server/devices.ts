/**
 * Device registrations (US-7-06, data-model §11.1, docs/offline-sync.md §6). The device key is a
 * random secret generated by the PWA and kept in the device's local storage; only its sha256 is
 * stored. It identifies the installation, never the person (the session cookie does that).
 */
export type DeviceStatus = "pending" | "active" | "suspended" | "removed";
export type DeviceRow = typeof deviceRegistrations.$inferSelect;

/** Device state machine: pending → active | removed; active ⇄ suspended; any → removed (terminal). */
export const DEVICE_TRANSITIONS: Record<DeviceStatus, readonly DeviceStatus[]> = {
  pending: ["active", "removed"],
  active: ["suspended", "removed"],
  suspended: ["active", "removed"],
  removed: [],
};

function assertTransition(from: string, to: DeviceStatus) {
  if (!(DEVICE_TRANSITIONS[from as DeviceStatus] ?? []).includes(to)) {
    throw new DomainError("state", `This device is ${from}; it cannot become ${to}.`, { machine: "device_registration", from, to });
  }
}

const DEVICE_KEY_RE = /^[A-Za-z0-9_-]{32,128}$/;
export const looksLikeDeviceKey = (k: unknown): k is string => typeof k === "string" && DEVICE_KEY_RE.test(k);
export const hashDeviceKey = (key: string) => sha256(`device:${key}`);

export async function findDeviceByKey(organizationId: string, key: string | null | undefined): Promise<DeviceRow | null> {
  if (!looksLikeDeviceKey(key)) return null;
  const [row] = await db
    .select()
    .from(deviceRegistrations)
    .where(and(eq(deviceRegistrations.organizationId, organizationId), eq(deviceRegistrations.deviceKeyHash, hashDeviceKey(key))))
    .limit(1);
  return row ?? null;
}

/** Workflows a device may run offline: its grant ∩ the site policy (setting `offline.workflows`). */
export async function effectiveWorkflows(device: DeviceRow): Promise<OfflineWorkflow[]> {
  if (device.status !== "active") return [];
  const site = (await getSetting(db, device.organizationId, "offline.workflows", device.siteId)) as OfflineWorkflow[];
  return (device.allowedOfflineWorkflows as OfflineWorkflow[]).filter((w) => site.includes(w));
}

export async function deviceInfo(device: DeviceRow): Promise<DeviceInfo> {
  const [site] = await db.select({ code: sites.code }).from(sites).where(eq(sites.id, device.siteId)).limit(1);
  return { id: device.id, status: device.status as DeviceStatus, label: device.label, siteId: device.siteId, siteCode: site?.code ?? "", allowedWorkflows: await effectiveWorkflows(device) };
}

const RequestSchema = z
  .object({
    deviceKey: z.string().regex(DEVICE_KEY_RE, "The device key is malformed; reload the page and try again."),
    label: z.string().trim().min(3, "Name the device (at least 3 characters), e.g. Weighing tablet 1.").max(80),
    platform: z.enum(DEVICE_PLATFORMS).default("other"),
    browser: z.string().trim().max(80).nullable().optional(),
    deviceClass: z.enum(DEVICE_CLASSES).default("floor_shared"),
    siteId: z.uuid(),
  })
  .strict();

/**
 * Self-service: the signed-in person asks for this device to be registered at one of their sites.
 * The request waits for a device administrator (`pending`). Asking again from the same device
 * returns the existing registration; a removed device must generate a new key (the PWA does).
 */
export async function requestDeviceRegistration(ctx: AuthContext, input: unknown) {
  ctx.assertWritable();
  const p = RequestSchema.safeParse(input);
  if (!p.success) throw new DomainError("validation", p.error.issues[0]?.message ?? "Check the device details.", { fieldErrors: Object.fromEntries(p.error.issues.map((i) => [String(i.path[0] ?? "form"), i.message])) });
  const v = p.data;
  ctx.requireSite(v.siteId);
  const hash = hashDeviceKey(v.deviceKey);
  return db.transaction(async (tx) => {
    const [existing] = await tx.select().from(deviceRegistrations).where(and(eq(deviceRegistrations.organizationId, ctx.organizationId), eq(deviceRegistrations.deviceKeyHash, hash))).limit(1);
    if (existing) {
      if (existing.status === "removed") throw new DomainError("state", "This device was removed by an administrator. Reset the device on the Sync page to request a new registration.");
      return { deviceId: existing.id, status: existing.status, replayed: true };
    }
    const [open] = await tx
      .select({ n: sql<number>`count(*)::int` })
      .from(deviceRegistrations)
      .where(and(eq(deviceRegistrations.requestedBy, ctx.userId), eq(deviceRegistrations.status, "pending")));
    if ((open?.n ?? 0) >= 5) throw new DomainError("validation", "You already have 5 device requests waiting. Ask a device administrator to review them first.");
    const [row] = await tx
      .insert(deviceRegistrations)
      .values({
        organizationId: ctx.organizationId,
        siteId: v.siteId,
        deviceKeyHash: hash,
        label: v.label,
        platform: v.platform,
        browser: v.browser ?? null,
        deviceClass: v.deviceClass,
        status: "pending",
        requestedBy: ctx.userId,
        statusChangedBy: ctx.userId,
      })
      .returning();
    await audit(tx, ctx, { action: "platform.device.registration_requested", entityType: "device_registration", entityId: row.id, entityNumber: row.label, siteId: row.siteId, after: { label: row.label, platform: row.platform, deviceClass: row.deviceClass } });
    return { deviceId: row.id, status: row.status, replayed: false };
  });
}

async function lockDevice(ctx: AuthContext, tx: Tx, deviceId: string) {
  if (!z.uuid().safeParse(deviceId).success) throw new DomainError("not_found", "Device not found in your sites.");
  const [d] = await tx.select().from(deviceRegistrations).where(eq(deviceRegistrations.id, deviceId)).for("update").limit(1);
  if (!d || d.organizationId !== ctx.organizationId || !ctx.allowedSiteIds.includes(d.siteId)) throw new DomainError("not_found", "Device not found in your sites.");
  ctx.requireAt("platform.device.admin", d.siteId);
  return d;
}

const WorkflowsSchema = z.array(z.enum(OFFLINE_WORKFLOWS)).max(OFFLINE_WORKFLOWS.length);

/** Activates a pending or suspended device, or changes an active device's grants (`platform.device.admin` at its site). */
export async function activateDevice(ctx: AuthContext, input: { deviceId: string; workflows: string[]; label?: string | null; deviceClass?: string | null; isManaged?: boolean }) {
  const wf = WorkflowsSchema.safeParse([...new Set(input.workflows ?? [])]);
  if (!wf.success) throw new DomainError("validation", "Choose offline workflows from the list.", { field: "workflows" });
  const cls = input.deviceClass ? z.enum(DEVICE_CLASSES).safeParse(input.deviceClass) : null;
  if (cls && !cls.success) throw new DomainError("validation", "Choose the device class.", { field: "deviceClass" });
  const label = input.label?.trim();
  if (label !== undefined && label !== null && (label.length < 3 || label.length > 80)) throw new DomainError("validation", "The device name needs 3 to 80 characters.", { field: "label" });
  return db.transaction(async (tx) => {
    const d = await lockDevice(ctx, tx, input.deviceId);
    const updateOnly = d.status === "active";
    if (!updateOnly) assertTransition(d.status, "active");
    const now = new Date();
    const after = {
      status: "active" as const,
      allowedOfflineWorkflows: wf.data,
      label: label || d.label,
      deviceClass: cls?.success ? cls.data : d.deviceClass,
      isManaged: input.isManaged ?? d.isManaged,
    };
    await tx
      .update(deviceRegistrations)
      .set({
        ...after,
        registeredBy: d.registeredBy ?? ctx.userId,
        registeredAt: d.registeredAt ?? now,
        ...(updateOnly ? {} : { statusChangedAt: now, statusChangedBy: ctx.userId, statusReason: null }),
        updatedAt: now,
      })
      .where(eq(deviceRegistrations.id, d.id));
    await audit(tx, ctx, {
      action: updateOnly ? "platform.device.updated" : "platform.device.activated",
      entityType: "device_registration",
      entityId: d.id,
      entityNumber: after.label,
      siteId: d.siteId,
      before: { status: d.status, allowedOfflineWorkflows: d.allowedOfflineWorkflows, label: d.label, deviceClass: d.deviceClass, isManaged: d.isManaged },
      after,
    });
    return { deviceId: d.id, status: "active" as const };
  });
}

/** Suspends (reversible) or removes (terminal) a device; a reason is required. A removed device clears its local store on next open. */
export async function changeDeviceStatus(ctx: AuthContext, input: { deviceId: string; to: "suspended" | "removed"; reason: string }) {
  const reason = input.reason?.trim() ?? "";
  if (reason.length < 5) throw new DomainError("validation", "Give the reason (at least 5 characters).", { field: "reason" });
  if (input.to !== "suspended" && input.to !== "removed") throw new DomainError("validation", "Unknown device status.");
  return db.transaction(async (tx) => {
    const d = await lockDevice(ctx, tx, input.deviceId);
    assertTransition(d.status, input.to);
    const now = new Date();
    await tx
      .update(deviceRegistrations)
      .set({
        status: input.to,
        statusChangedAt: now,
        statusChangedBy: ctx.userId,
        statusReason: reason,
        ...(input.to === "removed" ? { removedAt: now, removedBy: ctx.userId, removedReason: reason } : {}),
        updatedAt: now,
      })
      .where(eq(deviceRegistrations.id, d.id));
    await audit(tx, ctx, {
      action: input.to === "removed" ? "platform.device.removed" : "platform.device.suspended",
      entityType: "device_registration",
      entityId: d.id,
      entityNumber: d.label,
      siteId: d.siteId,
      reason,
      before: { status: d.status },
      after: { status: input.to },
    });
    return { deviceId: d.id, status: input.to };
  });
}

/** Devices at the sites where the caller holds `platform.device.view` (newest first). */
export async function listDevices(ctx: AuthContext, f: { status?: string | null } = {}) {
  ctx.require("platform.device.view");
  const siteIds = ctx.allowedSiteIds.filter((s) => ctx.canAt("platform.device.view", s));
  if (!siteIds.length) return [];
  const conds = [eq(deviceRegistrations.organizationId, ctx.organizationId), inArray(deviceRegistrations.siteId, siteIds)];
  if (f.status && (["pending", "active", "suspended", "removed"] as string[]).includes(f.status)) conds.push(eq(deviceRegistrations.status, f.status));
  const rows = await db
    .select({ d: deviceRegistrations, siteCode: sites.code, requestedByName: users.displayName })
    .from(deviceRegistrations)
    .innerJoin(sites, eq(sites.id, deviceRegistrations.siteId))
    .innerJoin(users, eq(users.id, deviceRegistrations.requestedBy))
    .where(and(...conds))
    .orderBy(desc(deviceRegistrations.requestedAt))
    .limit(500);
  return rows.map(({ d, siteCode, requestedByName }) => ({
    id: d.id,
    siteId: d.siteId,
    siteCode,
    label: d.label,
    platform: d.platform,
    browser: d.browser,
    deviceClass: d.deviceClass,
    isManaged: d.isManaged,
    status: d.status as DeviceStatus,
    allowedOfflineWorkflows: d.allowedOfflineWorkflows as OfflineWorkflow[],
    requestedByName,
    requestedAt: d.requestedAt,
    registeredAt: d.registeredAt,
    lastSeenAt: d.lastSeenAt,
    lastSyncAt: d.lastSyncAt,
    lastReferenceRefreshAt: d.lastReferenceRefreshAt,
    maxClockSkewSeenSeconds: d.maxClockSkewSeenSeconds,
    statusReason: d.statusReason,
    canAdmin: ctx.canAt("platform.device.admin", d.siteId),
  }));
}

/** Records contact from the device (sync panel data: last seen, last sync, largest clock difference). */
export async function touchDevice(deviceId: string, a: { synced?: boolean; referenceRefreshed?: boolean; skewSeconds?: number }) {
  const now = new Date();
  await db
    .update(deviceRegistrations)
    .set({
      lastSeenAt: now,
      ...(a.synced ? { lastSyncAt: now } : {}),
      ...(a.referenceRefreshed ? { lastReferenceRefreshAt: now, referenceCursor: now.toISOString() } : {}),
      ...(a.skewSeconds !== undefined ? { maxClockSkewSeenSeconds: sql`greatest(${deviceRegistrations.maxClockSkewSeenSeconds}, ${Math.min(Math.abs(Math.round(a.skewSeconds)), 2_000_000_000)})` } : {}),
    })
    .where(eq(deviceRegistrations.id, deviceId));
}
