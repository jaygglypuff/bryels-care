import type { ReportOutput } from "./run";

/**
 * Printable HTML file of a report (ADR-026: the browser prints or saves as PDF). A pure function of
 * the output; every value is escaped. No script, no external resources (docs/security.md §4.3).
 */

const ESC: Record<string, string> = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
export const esc = (v: unknown) => String(v ?? "").replace(/[&<>"']/g, (c) => ESC[c]);

export function renderReportHtml(o: ReportOutput): string {
  const head = o.columns.map((c) => `<th${c.numeric ? ' class="n"' : ""}>${esc(c.header)}</th>`).join("");
  const body = o.rows
    .map((r) => `<tr>${o.columns.map((c) => `<td${c.numeric ? ' class="n"' : ""}>${esc(r[c.key])}</td>`).join("")}</tr>`)
    .join("\n");
  const kv = (rows: [string, string][]) => rows.map(([k, v]) => `<tr><th>${esc(k)}</th><td>${esc(v)}</td></tr>`).join("");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${esc(o.code)} · ${esc(o.title)}</title>
<style>
@page { size: A4 landscape; margin: 12mm; }
body { font: 11px/1.35 Inter, system-ui, sans-serif; color: #111; margin: 0; padding: 12px; }
h1 { font-size: 16px; margin: 0 0 2px; } .muted { color: #555; }
table { border-collapse: collapse; width: 100%; } thead { display: table-header-group; } tr { break-inside: avoid; }
.data th, .data td { border: 1px solid #bbb; padding: 3px 5px; text-align: left; vertical-align: top; } .data th { background: #eef3ee; }
.meta th { text-align: left; padding: 1px 8px 1px 0; font-weight: 600; white-space: nowrap; vertical-align: top; } .meta td { padding: 1px 0; }
.n { text-align: right; font-variant-numeric: tabular-nums; }
.notice { border: 1px solid #b45309; background: #fff7ed; padding: 6px 8px; margin: 8px 0; }
ol { padding-left: 18px; }
</style></head><body>
<header><h1>${esc(o.title)}</h1><p class="muted">${esc(o.code)} · ${esc(o.organizationName)} · ${esc(o.category)}</p></header>
<table class="meta"><tbody>
${kv([...o.filters, ["Generated at", o.generatedAtText], ["Generated by", o.generatedBy], ["Data freshness", o.freshness], ["Value label", `${o.valueLabel} (computed from posted records)`], ["Rows", String(o.rowCount)], ["Contains personal data", o.personalData ? "yes" : "no"]])}
</tbody></table>
${o.truncated ? `<p class="notice">Truncated: only the first ${esc(o.cap.toLocaleString("en-PH"))} rows are included. Narrow the filters for the rest.</p>` : ""}
${o.rows.length === 0 ? `<p class="notice">No rows match these filters.</p>` : `<table class="data"><thead><tr>${head}</tr></thead><tbody>\n${body}\n</tbody></table>`}
${o.summary.length ? `<table class="meta" style="margin-top:8px"><tbody>${kv(o.summary)}</tbody></table>` : ""}
<section><h2 style="font-size:12px;margin:10px 0 2px">Footnotes</h2><ol>${o.footnotes.map((f) => `<li>${esc(f)}</li>`).join("")}</ol></section>
</body></html>
`;
}
